#!/bin/sh
set -eu

#  Compare AdaLang Analyzer's --verify bounded-scalar proof obligations
#  against GNATprove's --mode=prove results, per obligation (same file, line,
#  check kind), over a curated subset of the AdaCore SPARK2014 gnatprove
#  testsuite (benchmarks/spark_testsuite/MANIFEST.tsv). Unlike the
#  single-project oracle corpora, this corpus is a per-test-directory loop:
#  each testsuite unit is analyzed on its own generated `test.gpr`, then the
#  shared compare.awk is run once per unit (basenames are unique *within* a
#  unit, so its (basename,line,kind) matching stays correct with no source
#  edits), and aggregate.awk sums the buckets across all units.

benchmark_dir=$(CDPATH= cd -- "$(dirname "$0")" && pwd)
repository_root=$(CDPATH= cd -- "$benchmark_dir/../.." && pwd)
spark_root=${SPARK2014_ROOT:?set SPARK2014_ROOT to the pinned AdaCore/spark2014 checkout (see README.md)}
results_dir=${RESULTS_DIR:-$repository_root/benchmark-results/spark_testsuite}
analyzer=${ANALYZER:-$repository_root/bin/adalang_analyzer}
manifest=${MANIFEST:-$benchmark_dir/MANIFEST.tsv}

#  A GNAT toolchain (gnatls) must be resolvable on PATH: without it,
#  Libadalang's project/runtime source-path lookup fails and triggers
#  FP-029 -- same rationale as benchmarks/sparknacl/ and the other corpora.
if [ "${ALIRE:-}" != "True" ]; then
   exec alr exec -- "$0" "$@"
fi

expected_rev=$(sed -n '1p' "$benchmark_dir/SPARK2014_REVISION" | cut -f1)
actual_rev=$(git -C "$spark_root" rev-parse HEAD 2>/dev/null || echo "")
if [ "$actual_rev" != "$expected_rev" ]; then
   echo "spark2014 revision mismatch: expected $expected_rev, found ${actual_rev:-<not a git checkout>}" >&2
   exit 1
fi

tests_root=$spark_root/testsuite/gnatprove/tests
if [ ! -d "$tests_root" ]; then
   echo "no $tests_root -- is SPARK2014_ROOT a full spark2014 checkout?" >&2
   exit 1
fi

gnatprove=${GNATPROVE:-}
if [ -z "$gnatprove" ]; then
   gnatprove=$(command -v gnatprove || true)
fi
if [ -z "$gnatprove" ] && [ -n "${HOME:-}" ] && [ -x "${HOME}/.alire/bin/gnatprove" ]; then
   gnatprove=${HOME}/.alire/bin/gnatprove
fi
if [ -z "$gnatprove" ]; then
   echo "GNATprove lane skipped: executable not found" >&2
   exit 1
fi

work=$results_dir/work
per_test=$results_dir/per-test
rm -rf "$work" "$per_test"
mkdir -p "$work" "$per_test"

#  The testsuite's own default project, as generated by
#  lib/python/test_support.py:generate_project_file when a unit ships no
#  .gpr -- reproduced verbatim so both tools see the same sources, Ada
#  version, and local configuration pragmas the testsuite intends.
write_default_gpr() {
   dst=$1
   cat >"$dst/test.gpr" <<'GPR'
project Test is
  package Compiler is
    for Default_Switches ("Ada") use ("-gnatws", "-gnatdk", "-gnatd.k", "-gnat2022");
    for Local_Configuration_Pragmas use "test.adc";
  end Compiler;
end Test;
GPR
   if [ ! -f "$dst/test.adc" ]; then
      cat >"$dst/test.adc" <<'ADC'
pragma SPARK_Mode (On);
pragma Profile (Ravenscar);
pragma Partition_Elaboration_Policy (Sequential);
ADC
   fi
}

count=0
while IFS=$(printf '\t') read -r test class n_src loc kinds; do
   case "$test" in ''|'#'*) continue ;; esac
   src=$tests_root/$test
   if [ ! -d "$src" ]; then
      echo "manifest unit missing from checkout: $test" >&2
      exit 1
   fi
   d=$work/$test
   mkdir -p "$d"
   #  Copy the unit's own config pragmas first (if any), then its sources.
   [ -f "$src/test.adc" ] && cp "$src/test.adc" "$d/"
   for f in "$src"/*.ads "$src"/*.adb; do
      [ -f "$f" ] && cp "$f" "$d/"
   done
   write_default_gpr "$d"

   status=0
   ( cd "$d" && "$analyzer" -Ptest.gpr --verify -q --no-config --format=json \
       --output=adalang-verify.json 2>adalang-verify.stderr ) || status=$?
   if [ "$status" -gt 1 ]; then
      echo "AdaLang verify lane failed on $test with status $status" >&2
      exit "$status"
   fi

   ( cd "$d" && "$gnatprove" -Ptest.gpr --mode=prove -f -q --output=oneline \
       --prover=z3,cvc5,altergo --steps=16000 --timeout=60 --report=statistics \
       >gnatprove-prove.oneline 2>&1 ) || true

   #  Scope GNATprove's log to the unit's own sources. GNATprove analyzes
   #  the full project closure (runtime generics, withed library units),
   #  AdaLang only the project's declared sources -- keeping closure
   #  messages would pile up thousands of one-sided "GNATprove-only"
   #  obligations that say nothing about agreement. Same -P scope asymmetry
   #  benchmarks/coap_spark/README.md documents.
   own_bases=$(cd "$d" && ls *.ads *.adb 2>/dev/null | sed 's/[].[]/\\&/g')
   : >"$d/gnatprove-prove.scoped"
   for b in $own_bases; do
      grep "^$b:" "$d/gnatprove-prove.oneline" >>"$d/gnatprove-prove.scoped" || true
   done

   awk -f "$benchmark_dir/compare.awk" -v corpus_label="spark_testsuite/$test" \
      "$d/adalang-verify.json" "$d/gnatprove-prove.scoped" \
      >"$per_test/$test.txt"
   count=$((count + 1))
done <"$manifest"

echo "ran $count units"

awk -f "$benchmark_dir/aggregate.awk" \
   "$manifest" "$per_test"/*.txt \
   >"$results_dir/comparison.txt"

cat "$results_dir/comparison.txt"
echo "spark_testsuite benchmark results written to $results_dir"
echo "  per-unit reports: $per_test/"

#  Non-zero exit if any unit showed possible unsoundness or a false positive.
if grep -Eq '^(POSSIBLE ADALANG UNSOUNDNESS|AdaLang false positives) *: *[1-9]' \
   "$results_dir/comparison.txt"; then
   echo "FAIL: possible unsoundness or false positive detected -- see comparison.txt" >&2
   exit 1
fi
