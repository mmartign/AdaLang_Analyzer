#!/bin/sh
set -eu

benchmark_dir=$(CDPATH= cd -- "$(dirname "$0")" && pwd)
repository_root=$(CDPATH= cd -- "$benchmark_dir/../.." && pwd)
coap_spark_root=${COAP_SPARK_ROOT:?set COAP_SPARK_ROOT to the pinned mgrojo/coap_spark checkout}
sparklib_root=${COAP_SPARK_SPARKLIB:?set COAP_SPARK_SPARKLIB to a deployed \`alr get sparklib=16.1.0\` crate directory (see README.md)}
results_dir=${RESULTS_DIR:-$repository_root/benchmark-results/coap_spark}
analyzer=${ANALYZER:-$repository_root/bin/adalang_analyzer}

#  A GNAT toolchain (specifically gnatls) must be resolvable on PATH: without
#  it, Libadalang's own project/runtime source-path lookup for with'd units
#  fails, which triggers FP-029 -- same rationale as benchmarks/sparknacl/,
#  benchmarks/saatana/, benchmarks/aws/, and benchmarks/libkeccak/'s run.sh.
#  Re-exec under this repository's own Alire environment supplies it.
if [ "${ALIRE:-}" != "True" ]; then
   exec alr exec -- "$0" "$@"
fi

expected_coap_spark=$(sed -n '1p' "$benchmark_dir/COAP_SPARK_REVISION")
expected_wolfssl=$(sed -n '2p' "$benchmark_dir/COAP_SPARK_REVISION")
actual_coap_spark=$(git -C "$coap_spark_root" rev-parse HEAD)
actual_wolfssl=$(git -C "$coap_spark_root/libs/wolfssl" rev-parse HEAD)

if [ "$actual_coap_spark" != "$expected_coap_spark" ]; then
   echo "coap_spark revision mismatch: expected $expected_coap_spark, found $actual_coap_spark" >&2
   exit 1
fi
if [ "$actual_wolfssl" != "$expected_wolfssl" ]; then
   echo "wolfssl submodule revision mismatch: expected $expected_wolfssl, found $actual_wolfssl" >&2
   exit 1
fi

#  coap_spark.gpr `with`s config/coap_spark_config.gpr, generated by Alire
#  and not checked into the repository. Run the one-time setup step before
#  run.sh, as documented in benchmarks/coap_spark/README.md.
if [ ! -f "$coap_spark_root/config/coap_spark_config.gpr" ]; then
   echo "coap_spark is not configured: run 'alr build --stop-after=generation' in $coap_spark_root first" >&2
   echo "see benchmarks/coap_spark/README.md" >&2
   exit 1
fi
if [ ! -f "$sparklib_root/sparklib.gpr" ]; then
   echo "COAP_SPARK_SPARKLIB ($sparklib_root) has no sparklib.gpr -- run 'alr get sparklib=16.1.0' first" >&2
   echo "see benchmarks/coap_spark/README.md" >&2
   exit 1
fi
mkdir -p "$sparklib_root/sparklib_lib" "$sparklib_root/sparklib_obj"

#  coap_spark's own root sparklib.gpr wrapper `extends "sparklib_external"`,
#  a project name that only exists inside Alire's *old* per-crate release
#  layout for the gnatprove=14.1.1 dependency coap_spark's own alire.toml
#  pins (`gnatprove = "^14.1.1"`, matched to the GNAT Community 2021
#  "Colibri" toolchain the upstream project's own CI uses). This benchmark
#  suite's GNATprove is FSF 16.1.0 (the same pin documented in
#  benchmarks/libkeccak/RESULTS_*.md and the other three benchmarks'
#  results), which bundles its own SPARKlib; loading both at once produces
#  "Append must denote exactly one subprogram" ambiguity errors from
#  duplicate unit copies, and gnatprove aborts before analyzing anything.
#  Rather than run this one benchmark on a different, inconsistent GNATprove
#  pin, COAP_SPARK_SPARKLIB points at Alire's `sparklib` crate release
#  16.1.0 -- built explicitly "for use with GNATprove FSF 16" -- deployed
#  standalone (`alr get sparklib=16.1.0`, outside coap_spark's own
#  workspace). Putting it first on GPR_PROJECT_PATH, ahead of
#  coap_spark_root itself, makes `with "sparklib.gpr";` in coap_spark.gpr
#  resolve to this project (also literally named `SPARKlib`) instead of the
#  repository's own sparklib.gpr wrapper -- no source edits to the pinned
#  checkout required. -XSPARKLIB_INSTALLED=False switches this crate's own
#  Root computation from the "installed inside a GNAT toolchain" layout
#  (which it is not, deployed standalone) to its bundled src/ directory.
export GPR_PROJECT_PATH="$sparklib_root${GPR_PROJECT_PATH:+:$GPR_PROJECT_PATH}"
export GPR_PROJECT_PATH="$GPR_PROJECT_PATH:$coap_spark_root:$coap_spark_root/libs/wolfssl/wrapper/Ada"

project=$coap_spark_root/coap_spark.gpr
scenario_args="-XSPARKLIB_INSTALLED=False"

mkdir -p "$results_dir"

status=0
/usr/bin/time -p -o "$results_dir/adalang-verify.time" \
  "$analyzer" "-P$project" $scenario_args --verify -q \
  --no-config --format=json \
  --output="$results_dir/adalang-verify.json" \
  2>"$results_dir/adalang-verify.stderr" || status=$?

#  Status 1 means findings/obligations were emitted. Higher statuses are
#  invocation or analysis failures and invalidate the run.
if [ "$status" -gt 1 ]; then
   echo "AdaLang verify lane failed with status $status" >&2
   exit "$status"
fi

if command -v jq >/dev/null 2>&1; then
   jq '{
     analyzedFiles: (.analysisConfiguration.analyzedFiles | length),
     proofSummary: .proofSummary,
     proofObligations: (.proofObligations | length)
   }' "$results_dir/adalang-verify.json" \
     >"$results_dir/adalang-verify-summary.json"
fi

gnatprove=${GNATPROVE:-}
if [ -z "$gnatprove" ]; then
   gnatprove=$(command -v gnatprove || true)
fi
if [ -z "$gnatprove" ] && [ -n "${HOME:-}" ] \
  && [ -x "${HOME}/.alire/bin/gnatprove" ]; then
   gnatprove=${HOME}/.alire/bin/gnatprove
fi

if [ -z "$gnatprove" ]; then
   echo "GNATprove lane skipped: executable not found" >&2
   exit 1
fi

#  coap_spark's own coap_spark.gpr carries a tuned Prove package
#  (--mode=silver, --prover=z3,cvc5,altergo,colibri, --steps=0,
#  --timeout=360, --memlimit=4000, --checks-as-errors=on, --warnings=error,
#  --counterexamples=on) but, like Saatana's own Prove package (see
#  benchmarks/saatana/run.sh), no --report switch -- GNATprove's default of
#  reporting only failed checks in --output=oneline mode, which leaves
#  almost nothing for compare.awk to match against AdaLang's obligations
#  (confirmed interactively: 42 messages total without --report=statistics,
#  7,858 with it, for the same run). --report=statistics adds an
#  "info: ... proved" line per successfully discharged check, matching
#  SPARKNaCl's and Saatana's own benchmark invocations. `colibri` in the
#  project's own --prover list is AdaCore's own experimental prover, not
#  part of this toolchain's Z3/CVC5/Alt-Ergo bundle; --prover=z3,cvc5,altergo
#  on the command line replaces the project's own list rather than only
#  adding to it, so this alone drops colibri without needing exclusion.
#  --steps=16000 --timeout=60 widens the project's own --steps=0
#  (unlimited-until-timeout) --timeout=360 down to the same budget
#  libkeccak's own Prove package uses, since this benchmark's much shorter
#  per-check timeout is what was actually exercised interactively; a wider
#  budget only closes further residuals, it does not open new ones.
status=0
/usr/bin/time -p -o "$results_dir/gnatprove-prove.time" \
  "$gnatprove" "-P$project" $scenario_args --mode=prove -f -q --output=oneline \
  --prover=z3,cvc5,altergo --steps=16000 --timeout=60 --report=statistics \
  >"$results_dir/gnatprove-prove.oneline" 2>&1 || status=$?
printf '%s\n' "$status" >"$results_dir/gnatprove-prove.status"

#  coap_spark_config.gpr's Build_Profile default (development vs. release)
#  depends on exactly how Alire last resolved the workspace, not something
#  this script controls -- search rather than hardcode one obj/<profile>/
#  path.
gnatprove_summary=$(find "$coap_spark_root/obj" -path '*/gnatprove/gnatprove.out' -print -quit 2>/dev/null || true)
if [ -n "$gnatprove_summary" ] && [ -f "$gnatprove_summary" ]; then
   cp "$gnatprove_summary" "$results_dir/gnatprove.out"
fi

awk -f "$benchmark_dir/compare.awk" \
  "$results_dir/adalang-verify.json" \
  "$results_dir/gnatprove-prove.oneline" \
  >"$results_dir/comparison.txt"

cat "$results_dir/comparison.txt"
echo "coap_spark benchmark results written to $results_dir"
